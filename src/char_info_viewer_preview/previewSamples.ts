export function buildCharacterPreviewSample(tier: number): PreviewTierSample {
  const normalizedTier = Math.min(Math.max(Math.round(tier) || 5, 5), 7);
  const 生命层级 = TIER_TEXT[normalizedTier] ?? '第五层级';

  return {
    tier: normalizedTier,
    生命层级,
    data: {
      ...BASE_DATA,
      姓名: TIER_NAME[normalizedTier] ?? BASE_DATA.姓名,
      种族: RACE_BY_TIER[normalizedTier] ?? BASE_DATA.种族,
      生命层级,
    },
  };
}

